#!/usr/bin/env python3
"""Generates the marks of the AI providers Tern runs through, from Simple Icons.

    python3 -I scripts/brandlogos.py <dir>

<dir> holds the icons' SVG files as the npm package simple-icons publishes them (icons/<slug>.svg), at the
versions in LOGOS. They are read as text: the script takes the path data of each file's one <path>,
checks that it is nothing but path commands and numbers, and writes Sources/Tern/Shared/BrandLogos.swift
with the path data made absolute (M L C Q A Z only, the same normaliser as scripts/hugeicons.py).

Licences: Simple Icons' path data is CC0 1.0 (public domain). The marks themselves are trademarks of
Anthropic (Claude) and OpenAI; Tern shows them only to name the provider it runs through.

OpenAI's icon left Simple Icons in 16.0.0 (simple-icons/simple-icons#13944: OpenAI's brand terms grant a
non-transferable permission, so a shared icon set can't redistribute it), so it comes from 15.22.0, the
last release with it. Simple Icons has no Codex mark; Codex is shown with OpenAI's.
"""

import re
import sys
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
from hugeicons import absolute, path_data  # noqa: E402

# Swift case, Simple Icons slug, simple-icons version, title, colour (Simple Icons' brand hex, or None
# for `text1`, so a black mark reads in light and dark).
LOGOS = [
    ("claude", "claude", "16.35.0", "Claude", 0xD97757),
    ("openAI", "openai", "15.22.0", "OpenAI", None),
]

ROOT = Path(__file__).resolve().parent.parent
PATH_DATA = re.compile(r"^[MmLlHhVvCcSsQqTtAaZz0-9eE.,+\- ]+$")


def read_path(svg):
    """The `d` of the file's single <path>, after checking the file is a 24×24 Simple Icons glyph."""
    text = svg.read_text()
    if 'viewBox="0 0 24 24"' not in text:
        raise SystemExit(f"{svg.name}: expected a 24×24 viewBox")
    paths = re.findall(r'<path\b[^>]*?\sd="([^"]*)"', text)
    if len(paths) != 1:
        raise SystemExit(f"{svg.name}: expected one <path>, found {len(paths)}")
    if not PATH_DATA.match(paths[0]):
        raise SystemExit(f"{svg.name}: the path data has characters that aren't path commands or numbers")
    return path_data(absolute(paths[0]))


def swift(logos):
    lines = [
        "// Generated by scripts/brandlogos.py from Simple Icons (path data CC0 1.0). Do not edit; change the script.",
        "// The marks are trademarks of Anthropic (Claude) and OpenAI, shown only to name the AI provider Tern runs",
        "// through.",
        "",
        "/// The AI providers' marks: filled path data on a 24×24 grid.",
        "enum BrandLogo: String, CaseIterable, Sendable {",
    ]
    lines += [f"    case {case}" for case, *_ in LOGOS]
    lines += [
        "",
        "    /// Absolute SVG path data (M L C Q A Z), filled with the nonzero rule.",
        "    var pathData: String {",
        "        switch self {",
    ]
    for case, slug, version, title, _ in LOGOS:
        lines.append(f"        case .{case}: // {title}, simple-icons {version} icons/{slug}.svg")
        lines.append(f'            "{logos[case]}"')
    lines += [
        "        }",
        "    }",
        "",
        "    /// The brand's own colour (Simple Icons' hex), or nil to draw in `text1`.",
        "    var brandColor: UInt32? {",
        "        switch self {",
    ]
    for case, _, _, _, color in LOGOS:
        lines.append(f"        case .{case}: {f'0x{color:06X}' if color is not None else 'nil'}")
    lines += ["        }", "    }", "}", ""]
    return "\n".join(lines)


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    source = Path(sys.argv[1])
    logos = {case: read_path(source / f"{slug}.svg") for case, slug, *_ in LOGOS}
    (ROOT / "Sources/Tern/Shared/BrandLogos.swift").write_text(swift(logos))
    print(f"{len(LOGOS)} logos written")


if __name__ == "__main__":
    main()
